create index if not exists shopper_activity_product_idx on public.shopper_activity (product_id);
create index if not exists shopper_activity_created_idx on public.shopper_activity (created_at desc);

-- The server fills in who the shopper is, so it cannot be spoofed from the browser.
create or replace function public.stamp_activity() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  new.user_id := auth.uid();
  new.user_email := (select email from auth.users where id = auth.uid());
  return new;
end;
$$;
drop trigger if exists stamp_activity on public.shopper_activity;
create trigger stamp_activity before insert on public.shopper_activity for each row execute function public.stamp_activity();

