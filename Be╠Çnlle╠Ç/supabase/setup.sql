-- ---------- Orders & customers ------------------------------------------------------
create table if not exists public.orders (
  id text primary key,
  user_id uuid references auth.users (id) on delete set null default auth.uid(),
  email text not null,
  customer jsonb not null default '{}'::jsonb,
  shipping_address jsonb not null default '{}'::jsonb,
  status text not null default 'pending' check (status in ('pending', 'processing', 'shipped', 'delivered', 'cancelled')),
  items jsonb not null default '[]'::jsonb,
  item_count int not null default 0,
  subtotal numeric(10,2) not null,
  shipping numeric(10,2) not null default 0,
  total numeric(10,2) not null,
  date timestamptz not null default now()
);
create index if not exists orders_user_idx on public.orders (user_id);
create index if not exists orders_email_idx on public.orders (email);

create table if not exists public.addresses (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null default auth.uid() references auth.users (id) on delete cascade,
  label text not null,
  name text not null,
  address text not null,
  city text not null,
  zip text not null,
  country text not null,
  is_default boolean not null default false,
  created_at timestamptz not null default now()
);
create unique index if not exists addresses_one_default on public.addresses (user_id) where is_default;

create table if not exists public.messages (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  email text not null,
  subject text not null default '',
  message text not null,
  read boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.subscribers (
  email text primary key,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

-- ---------- Money: where the owner receives payouts (admin only) ----------------------
-- Store identifiers only (till numbers, account names). Never put API secrets in this table.
create table if not exists public.payout_methods (
  id uuid primary key default gen_random_uuid(),
  type text not null check (type in ('mpesa', 'bank', 'paypal', 'card', 'other')),
  label text not null,
  details jsonb not null default '{}'::jsonb,
  enabled boolean not null default true,
  is_default boolean not null default false,
  created_at timestamptz not null default now()
);
create unique index if not exists payout_one_default on public.payout_methods ((true)) where is_default;

-- ---------- Shopper interest: what visitors added to carts / wishlists -------------------
create table if not exists public.shopper_activity (
  id bigint generated always as identity primary key,
  session_id text not null check (char_length(session_id) <= 64),
  user_id uuid,
  user_email text,
  kind text not null check (kind in ('add_to_cart', 'wishlist_add', 'wishlist_remove')),
  product_id text not null,
  qty int not null default 1 check (qty between 1 and 99),
  created_at timestamptz not null default now()
